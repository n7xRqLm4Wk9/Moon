--!nonstrict

--[[
	Moon - modular loader

	local Moon = loadstring(game:HttpGet("https://raw.githubusercontent.com/n7xRqLm4Wk9/Moon/main/Moon.lua"))()

	Downloads every file in src/ at the same time, then runs them through a tiny module system:
	each file receives `import` and returns what it exports (see src/Main.lua for the load order).

	Settings (set before loading, all optional):
		getgenv().MOON_BASE_URL    -- where the files live (default below)
		getgenv().MOON_DEV_FOLDER  -- e.g. "Moon/": read files from your executor workspace instead of GitHub

	Want one request instead of ~30? Load dist/Moon.bundle.lua (built by build.py) instead.
]]

local env = getgenv()
local BASE = env.MOON_BASE_URL or "https://raw.githubusercontent.com/n7xRqLm4Wk9/Moon/main/"
local DEV_FOLDER = env.MOON_DEV_FOLDER

-- MODULES:BEGIN (generated by build.py)
local MODULES = {
	"Core/Fonts",
	"Core/Moon",
	"Core/Services",
	"Core/Util",
	"Main",
	"Theme/Binding",
	"Theme/Colors",
	"Theme/Presets",
	"Theme/Registry",
	"UI/Card",
	"UI/Elements/Base",
	"UI/Elements/Button",
	"UI/Elements/ColorPicker",
	"UI/Elements/Dropdown",
	"UI/Elements/Helpers",
	"UI/Elements/Index",
	"UI/Elements/Keybind",
	"UI/Elements/Label",
	"UI/Elements/Section",
	"UI/Elements/Slider",
	"UI/Elements/Textbox",
	"UI/Elements/Toggle",
	"UI/Logo",
	"Window/Create",
	"Window/Notify",
	"Window/OpenButton",
	"Window/PlayerCard",
	"Window/Tab",
	"Window/Watermark",
	"Window/Window",
}
-- MODULES:END

local sources = {}

local function fetch(name: string): string
	local path = "src/" .. name .. ".lua"
	if DEV_FOLDER and isfile and isfile(DEV_FOLDER .. path) then
		return readfile(DEV_FOLDER .. path)
	end
	return game:HttpGet(BASE .. path)
end

-- download everything at the same time (one round trip instead of one per file)
local pending = #MODULES
for _, name in ipairs(MODULES) do
	task.spawn(function()
		local ok, result = pcall(fetch, name)
		if ok then
			sources[name] = result
		else
			warn("[Moon] could not download " .. name .. ": " .. tostring(result))
		end
		pending -= 1
	end)
end

local deadline = os.clock() + 30
while pending > 0 and os.clock() < deadline do
	task.wait()
end

local cache = {}

local function import(name: string)
	local cached = cache[name]
	if cached ~= nil then
		return cached
	end
	local source = sources[name] or fetch(name)
	local chunk, err = loadstring(source, "=Moon/" .. name)
	if not chunk then
		error("[Moon] could not compile " .. name .. ": " .. tostring(err), 0)
	end
	local result = chunk(import)
	if result == nil then
		result = true
	end
	cache[name] = result
	return result
end

return import("Main")
