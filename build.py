#!/usr/bin/env python3
"""
Moon build script.

  python3 build.py

1. Rewrites the module list in Moon.lua (between MODULES:BEGIN / MODULES:END) from the files in src/.
2. Writes dist/Moon.bundle.lua: every module in ONE file, so executors need a single HTTP request.

Run it after you add, remove or edit anything in src/, then commit dist/ too.
"""
import os
import re

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, "src")


def discover():
    names = []
    for dirpath, _, files in os.walk(SRC):
        for f in files:
            if f.endswith(".lua"):
                rel = os.path.relpath(os.path.join(dirpath, f), SRC)
                names.append(rel[:-4].replace(os.sep, "/"))
    return sorted(names)


def update_manifest(names):
    path = os.path.join(ROOT, "Moon.lua")
    text = open(path).read()
    block = "-- MODULES:BEGIN (generated by build.py)\nlocal MODULES = {\n"
    block += "".join(f'\t"{n}",\n' for n in names)
    block += "}\n-- MODULES:END"
    new = re.sub(r"-- MODULES:BEGIN.*?-- MODULES:END", lambda m: block, text, flags=re.S)
    open(path, "w").write(new)


def bundle(names):
    out = [
        "--!nonstrict",
        "-- Moon UI library - single-file bundle.",
        "-- Generated by build.py from src/. Do not edit this file, edit src/ and run build.py again.",
        "",
        "local modules = {}",
        "",
    ]
    for n in names:
        body = open(os.path.join(SRC, n + ".lua")).read().rstrip()
        out.append(f'modules["{n}"] = function(...)')
        out.append(body)
        out.append("end")
        out.append("")
    out += [
        "local cache = {}",
        "",
        "local function import(name)",
        "\tlocal cached = cache[name]",
        "\tif cached ~= nil then",
        "\t\treturn cached",
        "\tend",
        "\tlocal loader = modules[name]",
        '\tassert(loader, "[Moon] unknown module: " .. tostring(name))',
        "\tlocal result = loader(import)",
        "\tif result == nil then",
        "\t\tresult = true",
        "\tend",
        "\tcache[name] = result",
        "\treturn result",
        "end",
        "",
        'return import("Main")',
        "",
    ]
    os.makedirs(os.path.join(ROOT, "dist"), exist_ok=True)
    path = os.path.join(ROOT, "dist", "Moon.bundle.lua")
    open(path, "w").write("\n".join(out))
    return path


if __name__ == "__main__":
    names = discover()
    update_manifest(names)
    path = bundle(names)
    print(f"{len(names)} modules -> {os.path.relpath(path, ROOT)} ({os.path.getsize(path) // 1024} KB)")
